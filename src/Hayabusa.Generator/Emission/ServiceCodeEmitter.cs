using System;
using System.Globalization;
using System.Text;
using Hayabusa.Generator.Models;

namespace Hayabusa.Generator.Emission;

/// <summary>
/// Emits zero-allocation C# source code (<c>*.g.cs</c>) for `[HayabusaService]` classes,
/// including jump-table RPC dispatchers, Radix-style HTTP route matchers, and strongly-typed client proxies.
/// </summary>
internal static class ServiceCodeEmitter
{
    public static string EmitServiceSource(in ServiceModel model)
    {
        var sb = new StringBuilder(2048);
        AppendFileHeader(sb, model.Header.Namespace);

        string baseClause = model.Header.IsRoomActorSubclass
            ? string.Empty
            : " : global::Hayabusa.Rpc.IHayabusaRpcService";
        string modifier = model.Header.IsRoomActorSubclass ? "override" : "public";

        if (!model.Header.IsRoomActorSubclass)
        {
            sb.Append("public partial class ").Append(model.Header.ClassName).AppendLine(baseClause);
        }
        else
        {
            sb.Append("public partial class ").AppendLine(model.Header.ClassName);
        }

        sb.AppendLine("{");
        EmitRpcDispatchMethod(sb, in model, modifier);
        sb.AppendLine();
        EmitHttpDispatchMethod(sb, in model, modifier);
        sb.AppendLine("}");
        sb.AppendLine();
        EmitClientProxyClass(sb, in model);

        return sb.ToString();
    }

    private static void AppendFileHeader(StringBuilder sb, string ns)
    {
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS1591 // Missing XML comment");
        sb.AppendLine("#pragma warning disable CS1998 // Async method lacks 'await' operators when only synchronous or HTTP routes are defined");
        sb.AppendLine("#pragma warning disable CA1502 // Avoid excessive complexity in generated jump tables");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(ns))
        {
            sb.Append("namespace ").Append(ns).AppendLine(";");
            sb.AppendLine();
        }
    }

    private static void EmitRpcDispatchMethod(StringBuilder sb, in ServiceModel model, string modifier)
    {
        if (model.Header.IsRoomActorSubclass)
        {
            sb.Append("    public ").Append(modifier).AppendLine(" async global::System.Threading.Tasks.ValueTask<bool> TryDispatchRpcAsync(");
        }
        else
        {
            sb.Append("    ").Append(modifier).AppendLine(" async global::System.Threading.Tasks.ValueTask<bool> TryDispatchRpcAsync(");
        }

        sb.AppendLine("        global::Hayabusa.Rpc.HayabusaContext context,");
        sb.AppendLine("        global::Hayabusa.Core.Primitives.MethodId methodId,");
        sb.AppendLine("        global::System.ReadOnlyMemory<byte> payload,");
        sb.AppendLine("        global::System.Buffers.IBufferWriter<byte> responseWriter)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(context);");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(responseWriter);");

        if (model.Header.IsRoomActorSubclass)
        {
            sb.AppendLine("        this.Context = context;");
            sb.AppendLine("        this.CurrentTick = context.CurrentTick;");
        }

        sb.AppendLine("        switch (methodId.Value)");
        sb.AppendLine("        {");

        for (int i = 0; i < model.RpcMethods.Length; i++)
        {
            EmitSingleRpcCase(sb, model.RpcMethods[i]);
        }

        sb.AppendLine("            default:");
        sb.AppendLine("                return false;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static void EmitSingleRpcCase(StringBuilder sb, in RpcMethodModel rpc)
    {
        sb.Append("            case ").Append(rpc.MethodId).AppendLine(":");
        sb.AppendLine("            {");

        string invokeArgs = EmitRequestDeserialization(sb, rpc.Parameters);
        string awaitPrefix = rpc.ResponseType.IsAsync ? "await " : string.Empty;

        if (rpc.ResponseType.HasPayload)
        {
            sb.Append("                var result = ")
              .Append(awaitPrefix)
              .Append("this.")
              .Append(rpc.MethodName)
              .Append('(')
              .Append(invokeArgs)
              .AppendLine(");");
            sb.AppendLine("                global::Hayabusa.Rpc.Framing.FrameParser.WriteMemoryPackFrame(");
            sb.AppendLine("                    ref responseWriter,");
            sb.AppendLine("                    methodId,");
            sb.AppendLine("                    global::Hayabusa.Rpc.Framing.RpcFrameFlags.Response,");
            sb.AppendLine("                    in result);");
        }
        else
        {
            sb.Append("                ")
              .Append(awaitPrefix)
              .Append("this.")
              .Append(rpc.MethodName)
              .Append('(')
              .Append(invokeArgs)
              .AppendLine(");");
            sb.AppendLine("                global::Hayabusa.Rpc.Framing.FrameParser.WriteFrame(");
            sb.AppendLine("                    ref responseWriter,");
            sb.AppendLine("                    methodId,");
            sb.AppendLine("                    global::Hayabusa.Rpc.Framing.RpcFrameFlags.Response,");
            sb.AppendLine("                    global::System.ReadOnlySpan<byte>.Empty);");
        }

        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
    }

    private static string EmitRequestDeserialization(StringBuilder sb, EquatableArray<RpcParameterModel> parameters)
    {
        if (parameters.Length == 0)
        {
            return string.Empty;
        }

        if (parameters.Length == 1)
        {
            sb.Append("                var request = global::MemoryPack.MemoryPackSerializer.Deserialize<")
              .Append(parameters[0].TypeFullName)
              .AppendLine(">(payload.Span);");
            return "request!";
        }

        string tupleType = BuildTupleTypeString(parameters);
        sb.Append("                var request = global::MemoryPack.MemoryPackSerializer.Deserialize<")
          .Append(tupleType)
          .AppendLine(">(payload.Span);");
        return BuildTupleItemArguments(parameters.Length);
    }

    private static string BuildTupleTypeString(EquatableArray<RpcParameterModel> parameters)
    {
        var sb = new StringBuilder("(");
        for (int i = 0; i < parameters.Length; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            sb.Append(parameters[i].TypeFullName);
        }

        sb.Append(')');
        return sb.ToString();
    }

    private static string BuildTupleItemArguments(int count)
    {
        var sb = new StringBuilder();
        for (int i = 1; i <= count; i++)
        {
            if (i > 1)
            {
                sb.Append(", ");
            }

            sb.Append("request.Item").Append(i.ToString(CultureInfo.InvariantCulture)).Append('!');
        }

        return sb.ToString();
    }

    private static void EmitHttpDispatchMethod(StringBuilder sb, in ServiceModel model, string modifier)
    {
        if (model.Header.IsRoomActorSubclass)
        {
            sb.Append("    public ").Append(modifier).AppendLine(" bool TryDispatchHttp(");
        }
        else
        {
            sb.Append("    ").Append(modifier).AppendLine(" bool TryDispatchHttp(");
        }

        sb.AppendLine("        global::Hayabusa.Rpc.HayabusaContext context,");
        sb.AppendLine("        in global::Hayabusa.Rpc.Http.HttpRequestView request,");
        sb.AppendLine("        global::System.Buffers.IBufferWriter<byte> responseWriter)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(context);");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(responseWriter);");

        for (int i = 0; i < model.HttpRoutes.Length; i++)
        {
            EmitSingleHttpRouteBranch(sb, model.HttpRoutes[i]);
        }

        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
    }

    private static void EmitSingleHttpRouteBranch(StringBuilder sb, in HttpRouteModel route)
    {
        sb.Append("        if (request.Method == global::Hayabusa.Rpc.Http.HttpMethodKind.")
          .Append(route.HttpVerb);

        if (string.IsNullOrEmpty(route.BoundParameter.Name))
        {
            byte[] utf8Bytes = Encoding.UTF8.GetBytes(route.RouteTemplate);
            sb.Append(" && request.Path.Length == ")
              .Append(utf8Bytes.Length)
              .Append(" && global::System.MemoryExtensions.SequenceEqual(request.Path, \"")
              .Append(route.RouteTemplate)
              .AppendLine("\"u8))");
            sb.AppendLine("        {");
            sb.Append("            this.").Append(route.MethodName).AppendLine("();");
            sb.AppendLine("            global::Hayabusa.Rpc.Http.HttpResponseWriter.WriteOkUtf8(ref responseWriter, \"OK\"u8);");
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
        }
        else
        {
            EmitParameterizedHttpRouteBranch(sb, in route);
        }
    }

    private static void EmitParameterizedHttpRouteBranch(StringBuilder sb, in HttpRouteModel route)
    {
        int braceIdx = route.RouteTemplate.IndexOf('{');
        string prefix = route.RouteTemplate.Substring(0, braceIdx);
        sb.Append(" && request.Path.Length > ")
          .Append(prefix.Length)
          .Append(" && global::System.MemoryExtensions.StartsWith(request.Path, \"")
          .Append(prefix)
          .AppendLine("\"u8))");
        sb.AppendLine("        {");
        sb.Append("            global::System.ReadOnlySpan<byte> seg = request.Path.Slice(").Append(prefix.Length).AppendLine(");");
        EmitZeroAllocRouteParameterBinding(sb, route.MethodName, route.BoundParameter.TypeFullName);
        sb.AppendLine("            global::Hayabusa.Rpc.Http.HttpResponseWriter.WriteOkUtf8(ref responseWriter, \"OK\"u8);");
        sb.AppendLine("            return true;");
        sb.AppendLine("        }");
    }

    private static void EmitZeroAllocRouteParameterBinding(StringBuilder sb, string methodName, string paramType)
    {
        if (paramType is "int" or "long" or "ulong" or "uint" or "global::System.Guid")
        {
            sb.Append("            if (!global::System.Buffers.Text.Utf8Parser.TryParse(seg, out ")
              .Append(paramType)
              .AppendLine(" parsedVal, out int consumed) || consumed != seg.Length)")
              .AppendLine("            {")
              .AppendLine("                return false;")
              .AppendLine("            }")
              .Append("            this.").Append(methodName).AppendLine("(parsedVal);");
            return;
        }

        if (paramType == "global::System.ReadOnlySpan<byte>")
        {
            sb.Append("            this.").Append(methodName).AppendLine("(seg);");
            return;
        }

        sb.AppendLine("            string paramVal = global::System.Text.Encoding.UTF8.GetString(seg);");
        sb.Append("            this.").Append(methodName).AppendLine("(paramVal);");
    }

    private static void EmitClientProxyClass(StringBuilder sb, in ServiceModel model)
    {
        string clientClassName = model.Header.ClassName + "Client";
        sb.Append("public sealed class ").Append(clientClassName).AppendLine(" : global::System.IDisposable");
        sb.AppendLine("{");
        EmitClientInfrastructureMembers(sb, clientClassName);

        for (int i = 0; i < model.RpcMethods.Length; i++)
        {
            RpcMethodModel rpc = model.RpcMethods[i];
            EmitClientWriteFrameMethod(sb, in rpc);
            EmitClientAsyncCallMethod(sb, in rpc);
        }

        sb.AppendLine("}");
    }

    private static void EmitClientInfrastructureMembers(StringBuilder sb, string clientClassName)
    {
        sb.AppendLine("    private readonly global::Hayabusa.Rpc.Client.HayabusaRpcClient _client;");
        sb.AppendLine("    private readonly bool _ownsClient;");
        sb.AppendLine();
        sb.Append("    public ").Append(clientClassName).AppendLine("(global::Hayabusa.Rpc.Client.HayabusaRpcClient client, bool ownsClient = false)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(client);");
        sb.AppendLine("        _client = client;");
        sb.AppendLine("        _ownsClient = ownsClient;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append("    public static async global::System.Threading.Tasks.ValueTask<").Append(clientClassName).AppendLine("> ConnectAsync(");
        sb.AppendLine("        string host,");
        sb.AppendLine("        int port = 5001,");
        sb.AppendLine("        global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine("    {");
        sb.AppendLine("        var client = await global::Hayabusa.Rpc.Client.HayabusaRpcClient.ConnectAsync(host, port, cancellationToken);");
        sb.Append("        return new ").Append(clientClassName).AppendLine("(client, ownsClient: true);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append("    public static ").Append(clientClassName).AppendLine(" CreateInMemory(global::Hayabusa.Rpc.Dispatcher.RpcDispatcher dispatcher)");
        sb.AppendLine("    {");
        sb.AppendLine("        var client = global::Hayabusa.Rpc.Client.HayabusaRpcClient.CreateInMemory(dispatcher);");
        sb.Append("        return new ").Append(clientClassName).AppendLine("(client, ownsClient: true);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Dispose()");
        sb.AppendLine("    {");
        sb.AppendLine("        if (_ownsClient)");
        sb.AppendLine("        {");
        sb.AppendLine("            _client.Dispose();");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static void EmitClientWriteFrameMethod(StringBuilder sb, in RpcMethodModel rpc)
    {
        sb.AppendLine();
        if (rpc.Parameters.Length == 0)
        {
            sb.Append("    public static void Write").Append(rpc.MethodName).AppendLine("Request<TWriter>(ref TWriter writer)")
              .AppendLine("        where TWriter : global::System.Buffers.IBufferWriter<byte>, allows ref struct")
              .AppendLine("    {")
              .Append("        global::Hayabusa.Rpc.Framing.FrameParser.WriteFrame(ref writer, new global::Hayabusa.Core.Primitives.MethodId(")
              .Append(rpc.MethodId)
              .AppendLine("), global::Hayabusa.Rpc.Framing.RpcFrameFlags.None, global::System.ReadOnlySpan<byte>.Empty);")
              .AppendLine("    }");
            return;
        }

        if (rpc.Parameters.Length == 1)
        {
            sb.Append("    public static void Write").Append(rpc.MethodName).Append("Request<TWriter>(ref TWriter writer, in ")
              .Append(rpc.Parameters[0].TypeFullName).AppendLine(" request)")
              .AppendLine("        where TWriter : global::System.Buffers.IBufferWriter<byte>, allows ref struct")
              .AppendLine("    {")
              .Append("        global::Hayabusa.Rpc.Framing.FrameParser.WriteMemoryPackFrame(ref writer, new global::Hayabusa.Core.Primitives.MethodId(")
              .Append(rpc.MethodId)
              .AppendLine("), global::Hayabusa.Rpc.Framing.RpcFrameFlags.None, in request);")
              .AppendLine("    }");
            return;
        }

        sb.Append("    public static void Write").Append(rpc.MethodName).Append("Request<TWriter>(ref TWriter writer, ")
          .Append(BuildParameterDeclarationList(rpc.Parameters)).AppendLine(")")
          .AppendLine("        where TWriter : global::System.Buffers.IBufferWriter<byte>, allows ref struct")
          .AppendLine("    {")
          .Append("        var payload = (").Append(BuildParameterNameList(rpc.Parameters)).AppendLine(");")
          .Append("        global::Hayabusa.Rpc.Framing.FrameParser.WriteMemoryPackFrame(ref writer, new global::Hayabusa.Core.Primitives.MethodId(")
          .Append(rpc.MethodId)
          .AppendLine("), global::Hayabusa.Rpc.Framing.RpcFrameFlags.None, in payload);")
          .AppendLine("    }");
    }

    private static void EmitClientAsyncCallMethod(StringBuilder sb, in RpcMethodModel rpc)
    {
        sb.AppendLine();
        string methodName = rpc.MethodName.EndsWith("Async", StringComparison.Ordinal)
            ? rpc.MethodName
            : rpc.MethodName + "Async";
        string returnType = rpc.ResponseType.HasPayload
            ? $"global::System.Threading.Tasks.ValueTask<{rpc.ResponseType.FullName}>"
            : "global::System.Threading.Tasks.ValueTask";

        sb.Append("    public ").Append(returnType).Append(' ').Append(methodName).Append('(');
        if (rpc.Parameters.Length > 0)
        {
            sb.Append(BuildParameterDeclarationList(rpc.Parameters)).Append(", ");
        }

        sb.AppendLine("global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine("    {");
        EmitClientAsyncCallBody(sb, in rpc);
        sb.AppendLine("    }");
    }

    private static void EmitClientAsyncCallBody(StringBuilder sb, in RpcMethodModel rpc)
    {
        string methodIdExpr = $"new global::Hayabusa.Core.Primitives.MethodId({rpc.MethodId})";
        if (rpc.Parameters.Length == 0)
        {
            string callName = rpc.ResponseType.HasPayload ? $"CallAsync<{rpc.ResponseType.FullName}>" : "CallVoidAsync";
            sb.Append("        return _client.").Append(callName).Append('(').Append(methodIdExpr).AppendLine(", cancellationToken);");
            return;
        }

        string reqType = rpc.Parameters.Length == 1
            ? rpc.Parameters[0].TypeFullName
            : BuildTupleTypeString(rpc.Parameters);
        string reqArg = rpc.Parameters.Length == 1
            ? rpc.Parameters[0].Name
            : $"({BuildParameterNameList(rpc.Parameters)})";

        string genericCall = rpc.ResponseType.HasPayload
            ? $"CallAsync<{reqType}, {rpc.ResponseType.FullName}>"
            : $"CallVoidAsync<{reqType}>";
        sb.Append("        return _client.").Append(genericCall).Append('(').Append(methodIdExpr).Append(", ").Append(reqArg).AppendLine(", cancellationToken);");
    }

    private static string BuildParameterDeclarationList(EquatableArray<RpcParameterModel> parameters)
    {
        var sb = new StringBuilder();
        for (int i = 0; i < parameters.Length; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            sb.Append(parameters[i].TypeFullName).Append(' ').Append(parameters[i].Name);
        }

        return sb.ToString();
    }

    private static string BuildParameterNameList(EquatableArray<RpcParameterModel> parameters)
    {
        var sb = new StringBuilder();
        for (int i = 0; i < parameters.Length; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            sb.Append(parameters[i].Name);
        }

        return sb.ToString();
    }
}
