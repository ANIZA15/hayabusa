using System.Text;
using Hayabusa.Generator.Models;

namespace Hayabusa.Generator.Emission;

/// <summary>
/// Emits zero-allocation C# source code (<c>*.g.cs</c>) for `[HayabusaService]` classes,
/// including jump-table RPC dispatchers, Radix-style HTTP route matchers, and strongly-typed client proxies.
/// </summary>
internal static class ServiceCodeEmitter
{
    public static string EmitServiceSource(in ServiceModel model)
    {
        var sb = new StringBuilder(2048);
        AppendFileHeader(sb, model.Header.Namespace);

        string baseClause = model.Header.IsRoomActorSubclass
            ? string.Empty
            : " : global::Hayabusa.Rpc.IHayabusaRpcService";
        string modifier = model.Header.IsRoomActorSubclass ? "override" : "public";

        if (!model.Header.IsRoomActorSubclass)
        {
            sb.Append("public partial class ").Append(model.Header.ClassName).AppendLine(baseClause);
        }
        else
        {
            sb.Append("public partial class ").AppendLine(model.Header.ClassName);
        }

        sb.AppendLine("{");
        EmitRpcDispatchMethod(sb, in model, modifier);
        sb.AppendLine();
        EmitHttpDispatchMethod(sb, in model, modifier);
        sb.AppendLine("}");
        sb.AppendLine();
        EmitClientProxyClass(sb, in model);

        return sb.ToString();
    }

    private static void AppendFileHeader(StringBuilder sb, string ns)
    {
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS1591 // Missing XML comment");
        sb.AppendLine("#pragma warning disable CS1998 // Async method lacks 'await' operators when only HTTP routes are defined");
        sb.AppendLine("#pragma warning disable CA1502 // Avoid excessive complexity in generated jump tables");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(ns))
        {
            sb.Append("namespace ").Append(ns).AppendLine(";");
            sb.AppendLine();
        }
    }

    private static void EmitRpcDispatchMethod(StringBuilder sb, in ServiceModel model, string modifier)
    {
        if (model.Header.IsRoomActorSubclass)
        {
            sb.Append("    public ").Append(modifier).AppendLine(" async global::System.Threading.Tasks.ValueTask<bool> TryDispatchRpcAsync(");
        }
        else
        {
            sb.Append("    ").Append(modifier).AppendLine(" async global::System.Threading.Tasks.ValueTask<bool> TryDispatchRpcAsync(");
        }

        sb.AppendLine("        global::Hayabusa.Rpc.HayabusaContext context,");
        sb.AppendLine("        global::Hayabusa.Core.Primitives.MethodId methodId,");
        sb.AppendLine("        global::System.ReadOnlyMemory<byte> payload,");
        sb.AppendLine("        global::System.Buffers.IBufferWriter<byte> responseWriter)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(context);");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(responseWriter);");

        if (model.Header.IsRoomActorSubclass)
        {
            sb.AppendLine("        this.Context = context;");
            sb.AppendLine("        this.CurrentTick = context.CurrentTick;");
        }

        sb.AppendLine("        switch (methodId.Value)");
        sb.AppendLine("        {");

        for (int i = 0; i < model.RpcMethods.Length; i++)
        {
            EmitSingleRpcCase(sb, model.RpcMethods[i]);
        }

        sb.AppendLine("            default:");
        sb.AppendLine("                return false;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static void EmitSingleRpcCase(StringBuilder sb, in RpcMethodModel rpc)
    {
        sb.Append("            case ").Append(rpc.MethodId).AppendLine(":");
        sb.AppendLine("            {");

        string invokeArgs = string.Empty;
        if (rpc.RequestType.HasParameter)
        {
            sb.Append("                var request = global::MemoryPack.MemoryPackSerializer.Deserialize<")
              .Append(rpc.RequestType.FullName)
              .AppendLine(">(payload.Span);");
            invokeArgs = "request!";
        }

        if (rpc.ResponseType.HasPayload)
        {
            sb.Append("                var result = await this.")
              .Append(rpc.MethodName)
              .Append('(')
              .Append(invokeArgs)
              .AppendLine(");");
            sb.AppendLine("                global::Hayabusa.Rpc.Framing.FrameParser.WriteMemoryPackFrame(");
            sb.AppendLine("                    ref responseWriter,");
            sb.AppendLine("                    methodId,");
            sb.AppendLine("                    global::Hayabusa.Rpc.Framing.RpcFrameFlags.Response,");
            sb.AppendLine("                    in result);");
        }
        else
        {
            sb.Append("                await this.")
              .Append(rpc.MethodName)
              .Append('(')
              .Append(invokeArgs)
              .AppendLine(");");
            sb.AppendLine("                global::Hayabusa.Rpc.Framing.FrameParser.WriteFrame(");
            sb.AppendLine("                    ref responseWriter,");
            sb.AppendLine("                    methodId,");
            sb.AppendLine("                    global::Hayabusa.Rpc.Framing.RpcFrameFlags.Response,");
            sb.AppendLine("                    global::System.ReadOnlySpan<byte>.Empty);");
        }

        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
    }

    private static void EmitHttpDispatchMethod(StringBuilder sb, in ServiceModel model, string modifier)
    {
        if (model.Header.IsRoomActorSubclass)
        {
            sb.Append("    public ").Append(modifier).AppendLine(" bool TryDispatchHttp(");
        }
        else
        {
            sb.Append("    ").Append(modifier).AppendLine(" bool TryDispatchHttp(");
        }

        sb.AppendLine("        global::Hayabusa.Rpc.HayabusaContext context,");
        sb.AppendLine("        in global::Hayabusa.Rpc.Http.HttpRequestView request,");
        sb.AppendLine("        global::System.Buffers.IBufferWriter<byte> responseWriter)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(context);");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(responseWriter);");

        for (int i = 0; i < model.HttpRoutes.Length; i++)
        {
            EmitSingleHttpRouteBranch(sb, model.HttpRoutes[i]);
        }

        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
    }

    private static void EmitSingleHttpRouteBranch(StringBuilder sb, in HttpRouteModel route)
    {
        sb.Append("        if (request.Method == global::Hayabusa.Rpc.Http.HttpMethodKind.")
          .Append(route.HttpVerb);

        if (string.IsNullOrEmpty(route.BoundParameterName))
        {
            sb.Append(" && global::System.MemoryExtensions.SequenceEqual(request.Path, \"")
              .Append(route.RouteTemplate)
              .AppendLine("\"u8))");
            sb.AppendLine("        {");
            sb.Append("            this.").Append(route.MethodName).AppendLine("();");
            sb.AppendLine("            global::Hayabusa.Rpc.Http.HttpResponseWriter.WriteOkUtf8(ref responseWriter, \"OK\"u8);");
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
        }
        else
        {
            int braceIdx = route.RouteTemplate.IndexOf('{');
            string prefix = route.RouteTemplate.Substring(0, braceIdx);
            sb.Append(" && global::System.MemoryExtensions.StartsWith(request.Path, \"")
              .Append(prefix)
              .AppendLine("\"u8))");
            sb.AppendLine("        {");
            sb.Append("            global::System.ReadOnlySpan<byte> seg = request.Path.Slice(").Append(prefix.Length).AppendLine(");");
            sb.AppendLine("            string paramVal = global::System.Text.Encoding.UTF8.GetString(seg);");
            sb.Append("            this.").Append(route.MethodName).AppendLine("(paramVal);");
            sb.AppendLine("            global::Hayabusa.Rpc.Http.HttpResponseWriter.WriteOkUtf8(ref responseWriter, \"OK\"u8);");
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
        }
    }

    private static void EmitClientProxyClass(StringBuilder sb, in ServiceModel model)
    {
        sb.Append("public static class ").Append(model.Header.ClassName).AppendLine("Client");
        sb.AppendLine("{");
        for (int i = 0; i < model.RpcMethods.Length; i++)
        {
            RpcMethodModel rpc = model.RpcMethods[i];
            if (rpc.RequestType.HasParameter)
            {
                sb.Append("    public static void Write")
                  .Append(rpc.MethodName)
                  .Append("Request<TWriter>(ref TWriter writer, in ")
                  .Append(rpc.RequestType.FullName)
                  .AppendLine(" request)")
                  .AppendLine("        where TWriter : global::System.Buffers.IBufferWriter<byte>, allows ref struct")
                  .AppendLine("    {")
                  .Append("        global::Hayabusa.Rpc.Framing.FrameParser.WriteMemoryPackFrame(ref writer, new global::Hayabusa.Core.Primitives.MethodId(")
                  .Append(rpc.MethodId)
                  .AppendLine("), global::Hayabusa.Rpc.Framing.RpcFrameFlags.None, in request);")
                  .AppendLine("    }");
            }
            else
            {
                sb.Append("    public static void Write")
                  .Append(rpc.MethodName)
                  .AppendLine("Request<TWriter>(ref TWriter writer)")
                  .AppendLine("        where TWriter : global::System.Buffers.IBufferWriter<byte>, allows ref struct")
                  .AppendLine("    {")
                  .Append("        global::Hayabusa.Rpc.Framing.FrameParser.WriteFrame(ref writer, new global::Hayabusa.Core.Primitives.MethodId(")
                  .Append(rpc.MethodId)
                  .AppendLine("), global::Hayabusa.Rpc.Framing.RpcFrameFlags.None, global::System.ReadOnlySpan<byte>.Empty);")
                  .AppendLine("    }");
            }
        }

        sb.AppendLine("}");
    }
}
